lines.append("// ProjectScopedTables 是带 project_id 的项目域业务表（对应 PROJECT_SCOPED_MODELS）。")
lines.append("var ProjectScopedTables = []string{")
for name in sorted(scoped_list):
    lines.append(f'\t"{name}",')
